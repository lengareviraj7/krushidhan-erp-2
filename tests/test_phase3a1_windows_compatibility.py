def test_tauri_lib_rs_windows_webview2_splash_and_export_contracts():
    lib_rs = (SRC_TAURI / "src" / "lib.rs").read_text(encoding="utf-8")

    # Splash navigation MUST allow Windows WebView2 http(s)://tauri.localhost alongside tauri://
    assert "fn is_allowed_splash_navigation" in lib_rs
    assert 'Some("tauri.localhost")' in lib_rs
    assert "is_allowed_splash_navigation(url)" in lib_rs

    # Encrypted .kdb.enc save dialog filter must be recognized
    assert '".kdb.enc"' in lib_rs

    # Export byte limit in Rust IPC must accommodate MAX_ENCRYPTED_ARCHIVE_BYTES
    m = re.search(r"const\s+MAX_EXPORT_BYTES\s*:\s*usize\s*=\s*(\d+)\s*\*\s*1024\s*\*\s*1024", lib_rs)
    assert m is not None, "MAX_EXPORT_BYTES constant missing in src-tauri/src/lib.rs"
    rust_max_export_bytes = int(m.group(1)) * 1024 * 1024
    assert rust_max_export_bytes >= MAX_ENCRYPTED_ARCHIVE_BYTES


