def test_tauri_conf_windows_commercial_installer_settings():
    conf_path = SRC_TAURI / "tauri.conf.json"
    conf = json.loads(conf_path.read_text(encoding="utf-8"))

    assert conf["identifier"] == APP_ID
    assert conf["productName"] == "Krushidhan ERP"

    csp = conf["app"]["security"]["csp"]
    assert "http://ipc.localhost" in csp
    assert "https://ipc.localhost" in csp

    bundle = conf["bundle"]
    assert bundle["active"] is True
    assert "icons/icon.ico" in bundle["icon"]
    assert (SRC_TAURI / "icons" / "icon.ico").is_file()
    assert "binaries/krushidhan-sidecar" in bundle["externalBin"]
    assert bundle.get("publisher") == "Krushidhan ERP"

    win_cfg = bundle.get("windows") or {}
    assert win_cfg.get("allowDowngrades") is False
    webview_mode = win_cfg.get("webviewInstallMode") or {}
    assert webview_mode.get("type") in {"embedBootstrapper", "offlineInstaller", "downloadBootstrapper"}

    # Must NEVER invent a fake code-signing thumbprint
    assert not win_cfg.get("certificateThumbprint")

    nsis = win_cfg.get("nsis") or {}
    assert nsis.get("installMode") == "currentUser"
    assert nsis.get("displayLanguageSelector") is False


