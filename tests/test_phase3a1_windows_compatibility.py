def test_windows_per_user_appdata_paths_never_target_install_dir():
    fake_win_env = {"LOCALAPPDATA": r"C:\Users\ShopOwner\AppData\Local"}
    app_dir = get_desktop_app_dir(env=fake_win_env, platform_name="win32")
    db_path = resolve_db_path(app_mode="desktop", env=fake_win_env)
    backup_dir = resolve_backup_dir(app_mode="desktop", env=fake_win_env)
    log_dir = resolve_log_dir(app_mode="desktop", env=fake_win_env)
    lock_path = get_desktop_lock_path(env=fake_win_env)

    # All persistent user files reside strictly inside %LOCALAPPDATA%\com.krushidhan.erp
    # (distinct from NSIS install dir %LOCALAPPDATA%\Krushidhan ERP)
    assert str(app_dir).endswith(APP_ID)
    assert "Krushidhan ERP" not in str(app_dir)
    assert str(db_path).startswith(str(app_dir))
    assert str(backup_dir).startswith(str(app_dir))
    assert str(log_dir).startswith(str(app_dir))
    assert str(lock_path).startswith(str(app_dir))


def test_windows_ctypes_64bit_signatures_in_backup_service_and_dpapi():
    bkp_src = (PROJECT_ROOT / "src" / "services" / "backup_service.py").read_text(encoding="utf-8")
    dpapi_src = (PROJECT_ROOT / "src" / "services" / "os_recovery_key_store.py").read_text(encoding="utf-8")

    # _is_process_alive must use WinDLL(..., use_last_error=True) + explicit 64-bit HANDLE restype/argtypes
    assert 'ctypes.WinDLL("kernel32", use_last_error=True)' in bkp_src
    assert "kernel32.OpenProcess.restype = ctypes.c_void_p" in bkp_src
    assert "kernel32.GetExitCodeProcess.argtypes" in bkp_src
    assert "kernel32.CloseHandle.argtypes = [ctypes.c_void_p]" in bkp_src

    # DPAPI must set explicit argtypes/restype on CryptProtectData, CryptUnprotectData, and LocalFree
    assert 'ctypes.WinDLL("crypt32", use_last_error=True)' in dpapi_src
    assert "c32.CryptProtectData.argtypes" in dpapi_src
    assert "c32.CryptUnprotectData.argtypes" in dpapi_src
    assert "k32.LocalFree.argtypes = [ctypes.c_void_p]" in dpapi_src
    assert "k32.LocalFree.restype = ctypes.c_void_p" in dpapi_src


